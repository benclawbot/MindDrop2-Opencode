export const getText = (key: keyof typeof APP_TEXT, params: Record<string, string> = {}) => {
  let text: string = APP_TEXT[key] || key
  Object.keys(params).forEach((param) => {
    const value = params[param]
    if (value !== undefined) {
      text = text.replace(`{${param}}`, value)
    }
  })
  return text
}
